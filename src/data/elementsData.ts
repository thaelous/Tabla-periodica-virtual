export function getElectronShells(z: number): number[] {
  const subshells = [
    { cap: 2, shell: 0 }, { cap: 2, shell: 1 }, { cap: 6, shell: 1 },
    { cap: 2, shell: 2 }, { cap: 6, shell: 2 }, { cap: 2, shell: 3 },
    { cap: 10, shell: 2 }, { cap: 6, shell: 3 }, { cap: 2, shell: 4 },
    { cap: 10, shell: 3 }, { cap: 6, shell: 4 }, { cap: 2, shell: 5 },
    { cap: 14, shell: 3 }, { cap: 10, shell: 4 }, { cap: 6, shell: 5 },
    { cap: 2, shell: 6 }, { cap: 14, shell: 4 }, { cap: 10, shell: 5 },
    { cap: 6, shell: 6 }
  ];
  let count = z;
  const shells = [0, 0, 0, 0, 0, 0, 0];
  for (const sub of subshells) {
    if (count <= 0) break;
    const take = Math.min(count, sub.cap);
    shells[sub.shell] += take;
    count -= take;
  }
  return shells.filter(n => n > 0);
}

